import assert from 'node:assert/strict';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import test from 'node:test';
import { buildSourceFrontend } from '../scripts/source-frontend.mjs';

function fixture(t, initial) {
  const root = mkdtempSync(join(tmpdir(), 'hp-source-frontend-'));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  writeFileSync(join(root, 'package.json'), JSON.stringify({ scripts: { 'bundle:release': 'build and sync' } }));
  const frontend = join(root, 'custom_components/houseplan/frontend');
  const materialize = value => { mkdirSync(frontend, { recursive: true }); writeFileSync(join(frontend, 'houseplan-card.js'), value); };
  if (initial !== undefined) materialize(initial);
  return { root, frontend, materialize };
}

test('#1598 source refs without a frontend snapshot install the fresh generated bytes', t => {
  const { root, frontend, materialize } = fixture(t), commands = [];
  const result = buildSourceFrontend(root, { ref: 'fixture-sha', log: () => {}, run: (cmd, args) => {
    commands.push([cmd, ...args]);
    if (cmd === 'node') materialize('fresh from dist');
  } });
  assert.match(result, /no committed frontend snapshot/);
  assert.equal(readFileSync(join(frontend, 'houseplan-card.js'), 'utf8'), 'fresh from dist');
  assert.equal(existsSync(join(root, '.committed-frontend')), false);
  assert.deepEqual(commands, [['npm', 'ci', '--ignore-scripts', '--no-audit', '--no-fund'], ['npm', 'run', 'build'], ['node', 'scripts/bundle-sync.mjs', '--release']]);
});

test('#1598 a failed source sync is an error rather than a committed-bundle fallback', t => {
  const { root } = fixture(t);
  assert.throws(() => buildSourceFrontend(root, { log: () => {}, run: cmd => {
    if (cmd === 'node') throw Error('manifest hash mismatch');
  } }), /manifest hash mismatch/);
});

test('#1010 a reproduced legacy snapshot keeps its committed byte identity', t => {
  const { root, frontend, materialize } = fixture(t, 'committed');
  const result = buildSourceFrontend(root, { log: () => {}, run: cmd => { if (cmd === 'node') materialize('committed'); } });
  assert.match(result, /^committed \(the build reproduces/);
  assert.equal(readFileSync(join(frontend, 'houseplan-card.js'), 'utf8'), 'committed');
  assert.equal(readFileSync(join(root, '.committed-frontend/houseplan-card.js'), 'utf8'), 'committed');
});

test('#1010 a stale legacy snapshot is replaced by the source build', t => {
  const { root, frontend, materialize } = fixture(t, 'old');
  const result = buildSourceFrontend(root, { log: () => {}, run: cmd => { if (cmd === 'node') materialize('new'); } });
  assert.match(result, /committed bundle lags/);
  assert.equal(readFileSync(join(frontend, 'houseplan-card.js'), 'utf8'), 'new');
});
